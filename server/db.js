const { Pool } = require("pg");

if (!process.env.DATABASE_URL) {
  throw new Error("DATABASE_URL must be set to connect to PostgreSQL.");
}

const pool = new Pool({
  connectionString: process.env.DATABASE_URL,
  ssl: process.env.PGSSLMODE === "require" ? { rejectUnauthorized: false } : false,
});

pool.on("error", (error) => {
  console.error("Unexpected PostgreSQL pool error:", error);
});

async function initializeDatabase() {
  await pool.query(`
    CREATE TABLE IF NOT EXISTS users (
      id TEXT PRIMARY KEY,
      role TEXT NOT NULL CHECK (role IN ('admin','customer','artisan')),
      fullname TEXT NOT NULL,
      email TEXT NOT NULL UNIQUE,
      phone TEXT,
      password_hash TEXT NOT NULL,
      status TEXT NOT NULL DEFAULT 'active',
      joined TEXT NOT NULL,
      skill TEXT,
      verified BOOLEAN NOT NULL DEFAULT FALSE,
      bio TEXT,
      rate TEXT,
      blood_type TEXT CHECK (blood_type IS NULL OR blood_type IN ('A','B','AB','O')),
      rhesus_factor TEXT CHECK (rhesus_factor IS NULL OR rhesus_factor IN ('positive','negative'))
    );

    CREATE TABLE IF NOT EXISTS bookings (
      id TEXT PRIMARY KEY,
      customer_id TEXT NOT NULL REFERENCES users(id),
      service TEXT NOT NULL,
      artisan_id TEXT NOT NULL REFERENCES users(id),
      date TEXT NOT NULL,
      status TEXT NOT NULL DEFAULT 'pending',
      price TEXT
    );

    CREATE TABLE IF NOT EXISTS appointments (
      id TEXT PRIMARY KEY,
      artisan_id TEXT NOT NULL REFERENCES users(id),
      department TEXT NOT NULL CHECK (department IN ('General OPD','Dental','Pediatrics')),
      date TEXT NOT NULL,
      status TEXT NOT NULL DEFAULT 'pending',
      created_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP
    );

    CREATE TABLE IF NOT EXISTS reviews (
      id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
      name TEXT NOT NULL,
      category TEXT NOT NULL,
      stars INTEGER NOT NULL,
      date TEXT NOT NULL,
      text TEXT NOT NULL
    );

    CREATE UNIQUE INDEX IF NOT EXISTS users_email_lower_idx ON users (lower(email));
  `);
}

module.exports = { pool, initializeDatabase };
