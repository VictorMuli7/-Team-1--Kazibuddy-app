/* ============================================================
   Jua Kali — PostgreSQL database layer
   Uses a shared connection pool (node-postgres). Configure it with
   DATABASE_URL (see .env.example). Tables are created on startup and
   the demo data is seeded once, only if the users table is empty.
   ============================================================ */

const bcrypt = require("bcryptjs");
const { Pool } = require("pg");

const pool = new Pool({
  // If DATABASE_URL is not set, pg falls back to the standard PG* env vars
  // (PGHOST, PGUSER, PGPASSWORD, PGDATABASE, PGPORT).
  connectionString: process.env.DATABASE_URL,
  // Hosted Postgres (Render, Neon, Supabase, Railway...) usually needs SSL.
  ssl: process.env.DATABASE_SSL === "true" ? { rejectUnauthorized: false } : undefined,
});

pool.on("error", (err) => {
  console.error("Unexpected PostgreSQL pool error:", err.message);
});

const query = (text, params) => pool.query(text, params);

// Arbitrary constant so concurrent server starts don't race on schema/seed.
const INIT_LOCK_ID = 727001;

const SCHEMA_SQL = `
  CREATE TABLE IF NOT EXISTS users (
    id            TEXT PRIMARY KEY,
    role          TEXT NOT NULL CHECK (role IN ('admin','customer','artisan')),
    fullname      TEXT NOT NULL,
    email         TEXT NOT NULL UNIQUE,
    phone         TEXT,
    password_hash TEXT NOT NULL,
    status        TEXT NOT NULL DEFAULT 'active',
    joined        TEXT NOT NULL,
    skill         TEXT,
    verified      BOOLEAN NOT NULL DEFAULT FALSE,
    bio           TEXT,
    rate          TEXT,
    blood_type    TEXT CHECK (blood_type IS NULL OR blood_type IN ('A','B','AB','O')),
    rhesus_factor TEXT CHECK (rhesus_factor IS NULL OR rhesus_factor IN ('positive','negative'))
  );

  CREATE UNIQUE INDEX IF NOT EXISTS users_email_lower_idx ON users (lower(email));

  CREATE TABLE IF NOT EXISTS bookings (
    id            TEXT PRIMARY KEY,
    customer_id   TEXT NOT NULL REFERENCES users(id),
    service       TEXT NOT NULL,
    artisan_id    TEXT NOT NULL REFERENCES users(id),
    date          TEXT NOT NULL,
    status        TEXT NOT NULL DEFAULT 'pending',
    price         TEXT
  );

  CREATE INDEX IF NOT EXISTS bookings_customer_idx ON bookings (customer_id);
  CREATE INDEX IF NOT EXISTS bookings_artisan_idx  ON bookings (artisan_id);

  CREATE TABLE IF NOT EXISTS appointments (
    id            TEXT PRIMARY KEY,
    artisan_id    TEXT NOT NULL REFERENCES users(id),
    department    TEXT NOT NULL CHECK (department IN ('General OPD','Dental','Pediatrics')),
    date          TEXT NOT NULL,
    status        TEXT NOT NULL DEFAULT 'pending',
    created_at    TIMESTAMPTZ NOT NULL DEFAULT NOW()
  );

  CREATE INDEX IF NOT EXISTS appointments_artisan_idx ON appointments (artisan_id);

  CREATE TABLE IF NOT EXISTS reviews (
    id            INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    name          TEXT NOT NULL,
    category      TEXT NOT NULL,
    stars         INTEGER NOT NULL,
    date          TEXT NOT NULL,
    text          TEXT NOT NULL
  );
`;

/* ---------- Create tables (safe to run repeatedly) ---------- */
async function initSchema(client) {
  await client.query(SCHEMA_SQL);
}

