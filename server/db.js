/* ---------- Run a function inside a transaction holding the init lock ---------- */
async function withInitLock(fn) {
  const client = await pool.connect();
  try {
    await client.query("BEGIN");
    await client.query("SELECT pg_advisory_xact_lock($1)", [INIT_LOCK_ID]);
    const result = await fn(client);
    await client.query("COMMIT");
    return result;
  } catch (err) {
    await client.query("ROLLBACK").catch(() => {});
    throw err;
  } finally {
    client.release();
  }
}

/* Creates the tables and seeds demo data if the database is empty.
   Call (and await) this once before the server starts listening. */
async function initDb() {
  await withInitLock(async (client) => {
    await initSchema(client);
    await seedIfNeeded(client);
  });
}

